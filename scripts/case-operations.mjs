#!/usr/bin/env node
// Rewrites shared/operations for a language's field-casing convention by adding
// aliases, so the server returns idiomatic keys and codegen types follow.
// See spec/03-sdk-design.md#casing.
//
//   camel: nested `release_year` becomes `releaseYear: release_year`
//   snake: unchanged (Python)
//
// Operation root fields are never aliased. They stay canonical so conformance
// cases, the scope map, and ActionError.operation match across languages.
// Arguments and input objects are untouched; they can't be aliased.
//
// CLI: node scripts/case-operations.mjs --case camel --out <dir>
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { Kind, parse, print, visit } from "graphql";

const toCamel = (name) => name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const CASES = {
  camel: toCamel,
  snake: null,
};

export function caseOperations(source, casing) {
  if (!(casing in CASES)) throw new Error(`Unknown casing "${casing}". Use: ${Object.keys(CASES).join(", ")}`);
  const convert = CASES[casing];
  if (!convert) return source;

  const document = visit(parse(source), {
    Field(node, _key, _parent, _path, ancestors) {
      if (node.alias || node.name.value.startsWith("__")) return undefined;
      // `ancestors` excludes the immediate parent (the selections array), so it
      // ends with [..., owner, SelectionSet].
      const owner = ancestors[ancestors.length - 2];
      if (owner?.kind === Kind.OPERATION_DEFINITION) return undefined;

      const aliased = convert(node.name.value);
      if (aliased === node.name.value) return undefined;
      return { ...node, alias: { kind: Kind.NAME, value: aliased } };
    },
  });
  return print(document);
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : path.endsWith(".graphql") ? [path] : [];
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = (flag) => {
    const i = process.argv.indexOf(flag);
    return i === -1 ? undefined : process.argv[i + 1];
  };
  const casing = arg("--case");
  const out = arg("--out");
  if (!casing || !out) {
    console.error("Usage: node scripts/case-operations.mjs --case <camel|snake> --out <dir>");
    process.exit(1);
  }

  const source = join(dirname(fileURLToPath(import.meta.url)), "../shared/operations");
  const files = walk(source);
  for (const file of files) {
    const target = join(out, relative(source, file));
    mkdirSync(dirname(target), { recursive: true });
    const header = `# Generated by scripts/case-operations.mjs (--case ${casing}) from shared/operations. Do not edit.\n`;
    writeFileSync(target, header + caseOperations(readFileSync(file, "utf8"), casing) + "\n");
  }
  console.log(`${files.length} files → ${out} (${casing})`);
}
