#!/usr/bin/env node
// Generates src/generated/enums.ts from shared/enums.json. Runs as part of
// `pnpm codegen`. Each enum becomes a const object plus a same-named type:
//   UserBookStatus.WantToRead === 1
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../../shared/enums.json", import.meta.url);
const target = new URL("../src/generated/enums.ts", import.meta.url);
const enums = JSON.parse(readFileSync(source, "utf8"));

const pascal = (key) => key.toLowerCase().replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());

let out = "// Generated by scripts/gen-enums.mjs from shared/enums.json. Do not edit.\n";
for (const [name, spec] of Object.entries(enums)) {
  if (!spec || typeof spec !== "object" || !Array.isArray(spec.values)) continue;
  const doc = [spec.notes, spec.source && `Source: ${spec.source}`].filter(Boolean).join(" ");
  out += `\n${doc ? `/** ${doc} */\n` : ""}export const ${name} = {\n`;
  for (const value of spec.values) {
    const doc = [value.label, value.doc].filter(Boolean).join(". ");
    if (doc) out += `  /** ${doc} */\n`;
    out += `  ${pascal(value.key)}: ${JSON.stringify(value.id)},\n`;
  }
  out += `} as const;\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];\n`;
}

writeFileSync(target, out);
console.log(`enums → ${target.pathname}`);
