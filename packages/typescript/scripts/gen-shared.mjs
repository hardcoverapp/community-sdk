#!/usr/bin/env node
// Generates the shared, language-neutral data into the package so it ships
// with it (nothing in src/ may import from outside the package). Runs as part
// of `pnpm codegen`.
//   shared/enums.json        → src/generated/enums.ts: a const object plus a
//                              same-named type per enum (UserBookStatus.WantToRead === 1)
//   shared/environments.json → src/generated/environments.ts
//   shared/auth.json         → src/generated/auth.ts: token prefixes and OAuth constants
//   shared/client.json       → src/generated/client.ts: defaults, retry waits, pacing,
//                              request cost, page sizes, User-Agent format
//   package.json version     → src/generated/version.ts (for the User-Agent)
import { readFileSync, writeFileSync } from "node:fs";

const shared = (name) => JSON.parse(readFileSync(new URL(`../../../shared/${name}`, import.meta.url), "utf8"));
const generated = (name) => new URL(`../src/generated/${name}`, import.meta.url);
const enums = shared("enums.json");

const pascal = (key) => key.toLowerCase().replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());

let out = "// Generated by scripts/gen-shared.mjs from shared/enums.json. Do not edit.\n";
for (const [name, spec] of Object.entries(enums)) {
  if (!spec || typeof spec !== "object" || !Array.isArray(spec.values)) continue;

  // Where the values come from is for maintainers (a line comment, not shipped).
  out += "\n";
  if (spec.source) out += `// Source: ${spec.source}\n`;

  // The enum's own doc lists every option, so hovering the name shows them.
  const doc = enumDoc(spec);
  out += doc;
  out += `export const ${name} = {\n`;
  for (const value of spec.values) {
    const valueDoc = [value.label, value.doc].filter(Boolean).join(". ");
    if (valueDoc) out += `  /** ${valueDoc} */\n`;
    out += `  ${pascal(value.key)}: ${JSON.stringify(value.id)},\n`;
  }
  out += `} as const;\n${doc}export type ${name} = (typeof ${name})[keyof typeof ${name}];\n`;
}

// "Notes, then one line per option: `Key` (id): label."
function enumDoc(spec) {
  const lines = [];

  if (spec.description) lines.push(spec.description, "");
  if (spec.notes) lines.push(spec.notes, "");
  if (spec.suggested && !spec.notes) lines.push("Suggested values, not a closed list: the SDK accepts any string and the server decides.", "");
  if (spec.field) lines.push(`The API field: \`${spec.field}\`.`, "");

  for (const value of spec.values) {
    const label = value.label ? `: ${value.label}` : "";
    lines.push(`- \`${pascal(value.key)}\` (${JSON.stringify(value.id)})${label}`);
  }

  return `/**\n${lines.map((line) => (line ? ` * ${line}` : " *")).join("\n")}\n */\n`;
}

writeFileSync(generated("enums.ts"), out);

// Environments: drop "$comment"/"$todo" notes; keep the endpoint map.
const environments = Object.fromEntries(
  Object.entries(shared("environments.json"))
    .filter(([key]) => !key.startsWith("$"))
    .map(([name, env]) => [name, Object.fromEntries(Object.entries(env).filter(([k]) => !k.startsWith("$")))]),
);
writeFileSync(
  generated("environments.ts"),
  "// Generated by scripts/gen-shared.mjs from shared/environments.json. Do not edit.\n\n" +
    `export const environments = ${JSON.stringify(environments, null, 2)} as const;\n\n` +
    "export type Environment = keyof typeof environments;\n",
);
// Auth rules: drop "$comment" notes, keep the data.
const withoutNotes = (value) =>
  Array.isArray(value)
    ? value.map(withoutNotes)
    : value && typeof value === "object"
      ? Object.fromEntries(Object.entries(value).filter(([k]) => !k.startsWith("$")).map(([k, v]) => [k, withoutNotes(v)]))
      : value;

// Plain data files (auth rules, client constants) become one const object each,
// named after the file, with the notes left behind in the JSON.
const writeConst = (name) =>
  writeFileSync(
    generated(`${name}.ts`),
    `// Generated by scripts/gen-shared.mjs from shared/${name}.json. Do not edit.\n\n` +
      `export const ${name} = ${JSON.stringify(withoutNotes(shared(`${name}.json`)), null, 2)} as const;\n`,
  );

writeConst("auth");
writeConst("client");
writeConst("stats");

const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
writeFileSync(
  generated("version.ts"),
  `// Generated by scripts/gen-shared.mjs from package.json. Do not edit.\n\nexport const version = ${JSON.stringify(version)};\n`,
);
console.log("enums.ts, environments.ts, auth.ts, client.ts, stats.ts, version.ts → src/generated/");
